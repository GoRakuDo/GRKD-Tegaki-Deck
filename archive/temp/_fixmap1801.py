# Verify
errors = []
for i in range(300):
    w = batch[i][3]; h = H[i]
    l = len(h)
    if l < 10 or l > 24:
        errors.append(f'LEN #{i+1801} {w} len={l} {h}')
    for k in w:
        if 0x4E00 <= ord(k) <= 0x9FFF and k in h:
            errors.append(f'LEAK #{i+1801} {w}: {k} in {h}')
if errors:
    for e in errors: print(e, file=sys.stderr)
    print(f'FAIL: {len(errors)} errors', file=sys.stderr)
    sys.exit(1)

print(f'ALL CLEAN! {len(H)} verified!', file=sys.stderr)

# Check which hints might be borderline (REVIEW_NEEDED candidates)
